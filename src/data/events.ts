export function eventsOn(date: string, origin: Origin | "All" = "All") {
  return events
    .filter((event) => event.date === date && (origin === "All" || event.origin === origin))
    .sort(byDateTime);
}

export function datesWithEvents(origin: Origin | "All" = "All") {
  const set = new Set<string>();
  for (const event of events) {
    if (origin === "All" || event.origin === origin) set.add(event.date);
  }
  return set;
}

export function getEvent(id: string) {
  return events.find((event) => event.id === id);
}
